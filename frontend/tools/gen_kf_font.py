#!/usr/bin/env python3
# Generates koriki_frame_font.h: the antialiased glyphs (8-bit alpha) that
# koriki_frame.c uses for the border texts, from Noto Sans (SIL OFL 1.1).
#   python3 frontend/tools/gen_kf_font.py > frontend/koriki_frame_font.h
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = "/usr/share/fonts/truetype/noto/"
CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ"
# name, font file, pixel size: tiny = texts on 320x240 screens, small = labels and the
# DMG band on 640x480, large = model name on 640x480
SIZES = [("tiny", "NotoSans-Bold.ttf", 7), ("small", "NotoSans-SemiBold.ttf", 11), ("large", "NotoSans-Bold.ttf", 16)]

out = sys.stdout
out.write("/* Generated by tools/gen_kf_font.py from Noto Sans (SIL Open Font License 1.1). */\n")
out.write("#ifndef KORIKI_FRAME_FONT_H\n#define KORIKI_FRAME_FONT_H\n#include <stdint.h>\n\n")
out.write("/* w x h bitmap at x + xoff; the pen moves adv (italic glyphs reach past it) */\n")
out.write("typedef struct { uint8_t w, adv; int8_t xoff; uint16_t off; } kf_glyph;\n")
out.write("typedef struct { uint8_t h; const kf_glyph *g; const uint8_t *a; } kf_font;\n")
out.write('#define KF_FONT_CHARS "%s"\n\n' % CHARS)

for name, file, size in SIZES:
    font = ImageFont.truetype(file if file.startswith("/") else FONTS + file, size)
    asc, desc = font.getmetrics()
    top = min(font.getbbox(c)[1] for c in CHARS if c != " ")
    bot = max(font.getbbox(c)[3] for c in CHARS if c != " ")
    h = bot - top
    glyphs, data = [], []
    pad = size // 2
    for c in CHARS:
        adv = int(round(font.getlength(c)))
        im = Image.new("L", (adv + 2 * pad, h), 0)
        ImageDraw.Draw(im).text((pad, -top), c, font=font, fill=255)
        box = im.getbbox()
        x0, x1 = (box[0], box[2]) if box else (pad, pad)
        px = im.load()
        glyphs.append((x1 - x0, adv, x0 - pad, len(data)))
        for y in range(h):
            for x in range(x0, x1):
                data.append(px[x, y])
    out.write("static const uint8_t kf_%s_alpha[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 24):
        out.write("  " + ",".join(str(v) for v in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write("static const kf_glyph kf_%s_glyphs[%d] = {" % (name, len(glyphs)))
    out.write(",".join("{%d,%d,%d,%d}" % g for g in glyphs))
    out.write("};\n")
    out.write("static const kf_font kf_font_%s = { %d, kf_%s_glyphs, kf_%s_alpha };\n\n" % (name, h, name, name))

out.write("#endif\n")
