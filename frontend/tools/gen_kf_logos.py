#!/usr/bin/env python3
# Generates frontend/koriki_frame_logos.h: the names of Koriki's RetroArch
# overlays (RetroArch/.retroarch/overlay/ATC), as grey levels (they are grey
# on black): koriki_frame.c draws them as the alpha of a white text.
#   python3 frontend/tools/gen_kf_logos.py > frontend/koriki_frame_logos.h
# gba: the name of the GBA SP overlay without "SP" (bigger than the one of
# ATC-GBA); gba_small: the same reduced to 20 lines, for the 3:2 picture
# centred on 640x480 (26 free lines under it, 3 of them the shadow).
import sys
from PIL import Image

ATC = "/opt/codes/Koriki/base/RetroArch/.retroarch/overlay/ATC/"
# name, overlay, box that holds the name (below the picture window), height
LOGOS = [("gba", "ATC-GBASP.png", (146, 430, 437, 480), None),
         ("gba_small", "ATC-GBASP.png", (146, 430, 437, 480), 20),
         ("sp", "ATC-GBASP.png", (0, 430, 640, 480), None)]

out = sys.stdout
out.write("/* Generated by tools/gen_kf_logos.py from Koriki's ATC overlays. */\n")
out.write("#ifndef KORIKI_FRAME_LOGOS_H\n#define KORIKI_FRAME_LOGOS_H\n#include <stdint.h>\n\n")
out.write("typedef struct { uint16_t w, h; const uint8_t *a; } kf_logo;\n\n")
for name, file, crop, height in LOGOS:
    im = Image.open(ATC + file).convert("RGBA")
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    bg.alpha_composite(im)
    grey = bg.convert("L").crop(crop)
    box = grey.point(lambda v: 255 if v > 8 else 0).getbbox()
    logo = grey.crop(box)
    if height:
        logo = logo.resize((round(logo.size[0] * height / logo.size[1]), height), Image.LANCZOS)
    w, h = logo.size
    data = list(logo.getdata())
    out.write("static const uint8_t kf_logo_%s_a[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 24):
        out.write("  " + ",".join(str(v) for v in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write("static const kf_logo kf_logo_%s = { %d, %d, kf_logo_%s_a };\n\n" % (name, w, h, name))
out.write("#endif\n")
